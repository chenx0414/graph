package gate

import (
	"bytes"
	"os"
	"path"
	"regexp"
	"strconv"
	"strings"
)

const (
	DefaultTokenLimit = 5000
	BytesPerToken     = 4
	HeadBytes         = 64 * 1024
)

var optOutPattern = regexp.MustCompile(`graph:allow-large-file[ \t]*:[ \t]*(\S[^\n]*)`)

var ignoredTrees = []string{
	".agents/skills/",
	"node_modules/",
	"vendor/",
	"third_party/",
	"third-party/",
	"dist/",
	"build/",
	"out/",
	"coverage/",
	".next/",
	"target/",
}

var ignoredNamePatterns = []*regexp.Regexp{
	regexp.MustCompile(`(^|/)pnpm-lock\.yaml$`),
	regexp.MustCompile(`(^|/)package-lock\.json$`),
	regexp.MustCompile(`(^|/)npm-shrinkwrap\.json$`),
	regexp.MustCompile(`(^|/)yarn\.lock$`),
	regexp.MustCompile(`(^|/)bun\.lockb?$`),
	regexp.MustCompile(`(^|/)[^/]*\.lock$`),
	regexp.MustCompile(`(^|/)[^/]*-lock\.json$`),
	regexp.MustCompile(`(^|/)go\.sum$`),
	regexp.MustCompile(`\.output\.txt$`),
	regexp.MustCompile(`\.snapshot\.json$`),
	regexp.MustCompile(`\.snap$`),
	regexp.MustCompile(`\.raw\.json$`),
}

var ignoredExtensions = map[string]bool{
	"png": true, "jpg": true, "jpeg": true, "gif": true, "webp": true, "avif": true, "bmp": true, "ico": true, "tif": true, "tiff": true, "svg": true,
	"pdf": true, "zip": true, "gz": true, "tgz": true, "bz2": true, "xz": true, "7z": true, "rar": true, "tar": true,
	"mp4": true, "webm": true, "mov": true, "avi": true, "mp3": true, "wav": true, "ogg": true, "flac": true,
	"woff": true, "woff2": true, "ttf": true, "otf": true, "eot": true,
	"sqlite": true, "sqlite3": true, "db": true, "wasm": true, "bin": true, "dat": true, "pack": true, "idx": true,
}

var generatedMarkers = []*regexp.Regexp{
	regexp.MustCompile(`@generated\b`),
	regexp.MustCompile(`Code generated .* DO NOT EDIT\.`),
	regexp.MustCompile(`\bDO NOT EDIT\b`),
	regexp.MustCompile(`(?i)auto[- ]?generated by`),
	regexp.MustCompile(`(?i)This file (?:was|is) (?:automatically )?generated`),
	regexp.MustCompile(`(?i)generated by (?:protoc|swagger|openapi|codegen)`),
}

type FileRecord struct {
	Path string
	Bytes int64
	Head []byte
}

type TokenFindings struct {
	Violations []FileRecord
	Skipped    []SkippedFile
}

type SkippedFile struct {
	Path   string
	Reason string
}

func TokenLimit(configured string) (int, error) {
	trimmed := strings.TrimSpace(configured)
	if trimmed == "" {
		return DefaultTokenLimit, nil
	}
	parsed, err := strconv.Atoi(trimmed)
	if err != nil || parsed <= 0 {
		return 0, &LimitError{Value: configured}
	}
	return parsed, nil
}

type LimitError struct{ Value string }

func (err *LimitError) Error() string {
	return "GRAPH_FILE_TOKEN_LIMIT must be a positive number, got \"" + err.Value + "\""
}

func extensionOf(target string) string {
	name := path.Base(target)
	dot := strings.LastIndex(name, ".")
	if dot <= 0 {
		return ""
	}
	return strings.ToLower(name[dot+1:])
}

func IgnoredByPath(target string) string {
	for _, tree := range ignoredTrees {
		if strings.HasPrefix(target, tree) {
			return "vendored or built tree"
		}
	}
	for _, pattern := range ignoredNamePatterns {
		if pattern.MatchString(target) {
			return "tool-owned file name"
		}
	}
	if ignoredExtensions[extensionOf(target)] {
		return "binary asset"
	}
	return ""
}

func headSlice(head []byte) []byte {
	if len(head) > HeadBytes {
		return head[:HeadBytes]
	}
	return head
}

func IsBinaryHead(head []byte) bool {
	return bytes.IndexByte(headSlice(head), 0) >= 0
}

func HasGeneratedMarker(head []byte) bool {
	text := string(headSlice(head))
	for _, marker := range generatedMarkers {
		if marker.MatchString(text) {
			return true
		}
	}
	return false
}

func OptOutReason(head []byte) string {
	match := optOutPattern.FindStringSubmatch(string(headSlice(head)))
	if match == nil {
		return ""
	}
	return strings.TrimSpace(match[1])
}

func CheckTokens(records []FileRecord, limit int) TokenFindings {
	findings := TokenFindings{Violations: []FileRecord{}, Skipped: []SkippedFile{}}
	maxBytes := int64(limit * BytesPerToken)
	for _, record := range records {
		if record.Bytes <= maxBytes {
			continue
		}
		if reason := IgnoredByPath(record.Path); reason != "" {
			findings.Skipped = append(findings.Skipped, SkippedFile{Path: record.Path, Reason: reason})
			continue
		}
		if reason := OptOutReason(record.Head); reason != "" {
			findings.Skipped = append(findings.Skipped, SkippedFile{Path: record.Path, Reason: "allowed in file: " + reason})
			continue
		}
		if IsBinaryHead(record.Head) {
			findings.Skipped = append(findings.Skipped, SkippedFile{Path: record.Path, Reason: "binary content"})
			continue
		}
		if HasGeneratedMarker(record.Head) {
			findings.Skipped = append(findings.Skipped, SkippedFile{Path: record.Path, Reason: "generated code"})
			continue
		}
		findings.Violations = append(findings.Violations, record)
	}
	return findings
}

func ReadFileRecord(root, target string) (FileRecord, bool) {
	full := path.Join(root, target)
	if !filepathIsFile(full) {
		return FileRecord{}, false
	}
	payload, err := os.ReadFile(full)
	if err != nil {
		return FileRecord{}, false
	}
	return FileRecord{Path: target, Bytes: int64(len(payload)), Head: headSlice(payload)}, true
}

func filepathIsFile(target string) bool {
	info, err := os.Stat(target)
	return err == nil && !info.IsDir()
}

func TokenTotal(record FileRecord) int {
	return int((record.Bytes + BytesPerToken - 1) / BytesPerToken)
}
