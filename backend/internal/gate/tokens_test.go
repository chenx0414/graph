package gate

import "testing"

func TestTokenLimitReadsTheConfiguredBudget(t *testing.T) {
	for _, test := range []struct {
		configured string
		want       int
		fails      bool
	}{
		{"", DefaultTokenLimit, false},
		{"   ", DefaultTokenLimit, false},
		{"120", 120, false},
		{"0", 0, true},
		{"-5", 0, true},
		{"abc", 0, true},
	} {
		limit, err := TokenLimit(test.configured)
		if test.fails {
			if err == nil || limit != 0 {
				t.Fatalf("%q must be rejected, got %d %v", test.configured, limit, err)
			}
			continue
		}
		if err != nil || limit != test.want {
			t.Fatalf("%q resolved to %d %v, want %d", test.configured, limit, err, test.want)
		}
	}
}

