func TestCheckTokensKeepsOnlyAgentAuthoredOversizedFiles(t *testing.T) {
	limit := 4
	oversized := int64(limit*BytesPerToken + 1)
	records := []FileRecord{
		{Path: "backend/small.go", Bytes: int64(limit * BytesPerToken), Head: []byte("package gate\n")},
		{Path: "backend/big.go", Bytes: oversized, Head: []byte("package gate\n")},
		{Path: "docs/big.md", Bytes: oversized, Head: []byte("graph:allow-large-file: a table of contents\n")},
		{Path: "backend/blob.bin", Bytes: oversized, Head: []byte{0, 1, 2}},
		{Path: "backend/generated.go", Bytes: oversized, Head: []byte("// Code generated by protoc. DO NOT EDIT.\n")},
		{Path: "dist/app/big", Bytes: oversized, Head: []byte("x")},
	}
	findings := CheckTokens(records, limit)
	if len(findings.Violations) != 1 || findings.Violations[0].Path != "backend/big.go" {
		t.Fatalf("only the agent-written oversized file may be refused, got %+v", findings.Violations)
	}
	if len(findings.Skipped) != 4 {
		t.Fatalf("the four exempt files must be reported as skipped, got %+v", findings.Skipped)
	}
	for _, skipped := range findings.Skipped {
		if skipped.Path == "docs/big.md" && skipped.Reason != "allowed in file: a table of contents" {
			t.Fatalf("the opt-out reason must reach the report, got %q", skipped.Reason)
		}
	}
}

func TestTokenTotalRoundsUp(t *testing.T) {
	if got := TokenTotal(FileRecord{Bytes: int64(BytesPerToken*3 + 1)}); got != 4 {
		t.Fatalf("a partial token still counts, got %d", got)
	}
	if got := TokenTotal(FileRecord{Bytes: 0}); got != 0 {
		t.Fatalf("an empty file has no tokens, got %d", got)
	}
}
