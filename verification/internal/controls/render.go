package controls

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// WriteAudit writes coverage.json next to the ledger plus a human-readable
// generated Markdown summary. The Markdown is generated, never hand-edited.
func WriteAudit(outDir string, report Report) (jsonPath, markdownPath string, err error) {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return "", "", err
	}
	jsonPath = filepath.Join(outDir, "coverage.json")
	raw, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		return "", "", err
	}
	if err := os.WriteFile(jsonPath, markGenerated(raw), 0o644); err != nil {
		return "", "", err
	}
	markdownPath = filepath.Join(outDir, "COVERAGE.generated.md")
	if err := os.WriteFile(markdownPath, []byte(RenderMarkdown(report)), 0o644); err != nil {
		return "", "", err
	}
	return jsonPath, markdownPath, nil
}

// RenderMarkdown is the generated summary: numbers first, then every control
// with its single conclusion and the command that proves or unblocks it.
func RenderMarkdown(report Report) string {
	var builder strings.Builder
	fmt.Fprintf(&builder, "<!-- generated by verify-graph cover audit; do not edit by hand -->\n")
	fmt.Fprintf(&builder, "# Control coverage\n\n")
	fmt.Fprintf(&builder, "- controls: **%d/%d covered**, %d not-applicable, %d blocked\n",
		report.Covered, report.Total, report.NotApplicable, report.Blocked)
	fmt.Fprintf(&builder, "- journeys cited: **%d**\n", report.Journeys)
	if len(report.Lanes) > 0 {
		fmt.Fprintf(&builder, "- lanes proven: %s\n", strings.Join(report.Lanes, ", "))
	}
	fmt.Fprintf(&builder, "- audit: %s / %s\n\n", report.Inventory, report.Ledger)
	if len(report.Problems) > 0 {
		fmt.Fprintf(&builder, "## Problems (%d)\n\n", len(report.Problems))
		for _, problem := range report.Problems {
			fmt.Fprintf(&builder, "- `%s` %s: %s\n", problem.Code, problem.Control, problem.Detail)
		}
		builder.WriteString("\n")
	}
	fmt.Fprintf(&builder, "## Controls\n\n")
	fmt.Fprintf(&builder, "| page | role | name | status | witness / reason |\n")
	fmt.Fprintf(&builder, "| --- | --- | --- | --- | --- |\n")
	for _, conclusion := range report.Conclusions {
		detail := conclusion.Reason
		if conclusion.Status == "covered" {
			detail = fmt.Sprintf("`%s` step %d (%s) — %s", conclusion.Journey, conclusion.Step, conclusion.Lane, conclusion.Reason)
		}
		if conclusion.Next != "" {
			detail += " — next: " + conclusion.Next
		}
		fmt.Fprintf(&builder, "| %s | %s | %s | %s | %s |\n",
			escapeCell(conclusion.Page), escapeCell(conclusion.Role), escapeCell(conclusion.Name),
			conclusion.Status, escapeCell(detail))
	}
	return builder.String()
}

func escapeCell(value string) string {
	value = strings.ReplaceAll(value, "|", "\\|")
	value = strings.ReplaceAll(value, "\n", " ")
	return strings.TrimSpace(value)
}
