#!/usr/bin/env node
/**
 * Pre-commit guard: no staged file may exceed the per-file context budget.
 *
 * Budget: 5,000 tokens per file, counted as bytes / 4 - the usual approximation
 * for source code and English text. A file past that budget cannot be read,
 * reviewed or refactored inside one context window, so it has to be split
 * before it enters the repository.
 *
 * Only staged content is measured, and the staged blob is what gets measured -
 * not the working tree. A file that was staged and then edited again is still
 * checked at the size it will have in the commit.
 *
 * Files an agent did not write are skipped, because splitting them is not the
 * agent's job: they are copied in by a tool, resolved by a package manager, or
 * emitted by a build step. Demanding a split of a lock file only produces a
 * patch nobody can review.
 *
 * Usage:
 *   node scripts/check-file-tokens.mjs            # check the staged files
 *   node scripts/check-file-tokens.mjs --changed  # check what the working tree changed
 *   node scripts/check-file-tokens.mjs <path>...  # check those files (working tree)
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const DEFAULT_TOKEN_LIMIT = 5000;
const BYTES_PER_TOKEN = 4;

/** How much of a file is read to classify it. Generated markers and asset
 *  signatures live at the top of a file, so the head is enough. */
const HEAD_BYTES = 64 * 1024;

/**
 * Where an author may write down that a file has to stay large.
 *
 * The reason has to sit on the same line as the marker, otherwise the marker
 * alone would silently exempt a file nobody justified.
 */
const OPT_OUT_PATTERN = /graph:allow-large-file[ \t]*:[ \t]*(\S[^\n]*)/;

/**
 * Trees that hold content copied in or produced by a tool.
 *
 * The guard asks "can this be fixed by splitting the file?" For these paths the
 * answer is no: they arrive from a package manager, an upstream repository or a
 * build step, so the only way to make them smaller is to stop vendoring them.
 */
const IGNORED_TREES = [
  '.agents/skills/', // vendored matt / pstack skill packages
  'node_modules/',
  'vendor/',
  'third_party/',
  'third-party/',
  'dist/',
  'build/',
  'out/',
  'coverage/',
  '.next/',
  'target/',
];

/** Single files that a script rewrites from an upstream source. */
const IGNORED_FILES = new Set([
  'src/catalog/models-dev.snapshot.json', // written by scripts/refresh-models-dev.mjs
]);

/** File names that a tool owns: lock files, captured output, snapshots. */
const IGNORED_NAME_PATTERNS = [
  /(^|\/)pnpm-lock\.yaml$/,
  /(^|\/)package-lock\.json$/,
  /(^|\/)npm-shrinkwrap\.json$/,
  /(^|\/)yarn\.lock$/,
  /(^|\/)bun\.lockb?$/,
  /(^|\/)[^/]*\.lock$/, // Cargo.lock, composer.lock, Gemfile.lock
  /(^|\/)[^/]*-lock\.json$/, // .agents/matt-skills-lock.json
  /(^|\/)go\.sum$/,
  /\.output\.txt$/, // captured command output
  /\.snapshot\.json$/,
  /\.snap$/, // vitest snapshots
  /\.raw\.json$/,
];

/**
 * Binary and asset files.
 *
 * They are payloads, not text: there is no line to split along, and an agent
 * never writes them by hand.
 */
const IGNORED_EXTENSIONS = new Set([
  'png', 'jpg', 'jpeg', 'gif', 'webp', 'avif', 'bmp', 'ico', 'tif', 'tiff', 'svg',
  'pdf', 'zip', 'gz', 'tgz', 'bz2', 'xz', '7z', 'rar', 'tar',
  'mp4', 'webm', 'mov', 'avi', 'mp3', 'wav', 'ogg', 'flac',
  'woff', 'woff2', 'ttf', 'otf', 'eot',
  'sqlite', 'sqlite3', 'db', 'wasm', 'bin', 'dat', 'pack', 'idx',
]);

/** Headers that mark a file as machine-written. */
const GENERATED_MARKERS = [
  /@generated\b/,
  /Code generated .* DO NOT EDIT\./,
  /\bDO NOT EDIT\b/,
  /auto[- ]?generated by/i,
  /This file (?:was|is) (?:automatically )?generated/i,
  /generated by (?:protoc|swagger|openapi|codegen)/i,
];

function tokenLimit() {
  const raw = process.env.GRAPH_FILE_TOKEN_LIMIT;
  if (raw === undefined || raw === '') return DEFAULT_TOKEN_LIMIT;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    console.error(`check-file-tokens: GRAPH_FILE_TOKEN_LIMIT must be a positive number, got "${raw}"`);
    process.exit(2);
  }
  return parsed;
}

function extensionOf(path) {
  const name = path.slice(path.lastIndexOf('/') + 1);
  const dot = name.lastIndexOf('.');
  if (dot <= 0) return '';
  return name.slice(dot + 1).toLowerCase();
}

/**
 * Whether the path itself already explains why the file is not agent-written.
 */
function ignoredByPath(path) {
  if (IGNORED_FILES.has(path)) return 'generated data file';
  if (IGNORED_TREES.some(tree => path.startsWith(tree))) return 'vendored or built tree';
  if (IGNORED_NAME_PATTERNS.some(pattern => pattern.test(path))) return 'tool-owned file name';
  if (IGNORED_EXTENSIONS.has(extensionOf(path))) return 'binary asset';
  return undefined;
}

function isBinary(head) {
  return head.subarray(0, HEAD_BYTES).includes(0);
}

function hasGeneratedMarker(head) {
  const text = head.subarray(0, HEAD_BYTES).toString('utf8');
  return GENERATED_MARKERS.some(marker => marker.test(text));
}

function optOutReason(head) {
  const text = head.subarray(0, HEAD_BYTES).toString('utf8');
  const match = OPT_OUT_PATTERN.exec(text);
  return match ? match[1].trim() : undefined;
}

/**
 * The staged paths that can hold content, as index entries.
 *
 * The change list is intersected with the index on purpose: a renamed file
 * reports its old path too, and that path is no longer in the index.
 */
function stagedEntries() {
  const changed = execFileSync(
    'git',
    ['diff', '--cached', '--name-only', '--diff-filter=ACMRT', '-z'],
    { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ).split('\0').filter(Boolean);

  const index = new Map();
  for (const record of execFileSync('git', ['ls-files', '-s', '-z'], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  }).split('\0').filter(Boolean)) {
    const tab = record.indexOf('\t');
    if (tab < 0) continue;
    const [mode, sha] = record.slice(0, tab).split(' ');
    index.set(record.slice(tab + 1), { mode, sha });
  }

  const entries = [];
  for (const path of changed) {
    const entry = index.get(path);
    if (!entry) continue; // deleted, or renamed away
    if (entry.mode === '160000') continue; // submodule
    if (entry.mode === '120000') continue; // symlink
    entries.push({ path, sha: entry.sha });
  }
  return entries;
}

/** Blob sizes for the given object names, in one git call. */
function blobSizes(shas) {
  const sizes = new Map();
  if (!shas.length) return sizes;
  const output = execFileSync('git', ['cat-file', '--batch-check'], {
    cwd: REPO_ROOT,
    input: `${shas.join('\n')}\n`,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  for (const line of output.split('\n')) {
    const [sha, type, size] = line.split(' ');
    if (type === 'blob' && size !== undefined) sizes.set(sha, Number(size));
  }
  return sizes;
}

function blobHead(sha) {
  const content = execFileSync('git', ['cat-file', 'blob', sha], {
    cwd: REPO_ROOT,
    encoding: 'buffer',
    maxBuffer: 256 * 1024 * 1024,
  });
  return content.subarray(0, HEAD_BYTES);
}

function fileRecords(paths) {
  const records = [];
  for (const path of paths) {
    const absolute = resolve(REPO_ROOT, path);
    const stats = statSync(absolute);
    if (!stats.isFile()) continue;
    records.push({
      path: relative(REPO_ROOT, absolute).split('\\').join('/'),
      bytes: stats.size,
      readHead: () => readFileSync(absolute).subarray(0, HEAD_BYTES),
    });
  }
  return records;
}

/**
 * The paths an uncommitted change touches: what the next commit would contain.
 *
 * The gate runs on a working tree, not on an index, and the self-improvement
 * path commits with the hooks skipped - so "staged" is empty exactly when the
 * budget most needs measuring. This is the same set the RSI guard calls dirty:
 * tracked files that differ from HEAD, plus the files nobody has added yet.
 */
function changedPaths() {
  const read = (args) => execFileSync('git', args, {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }).split('\0').filter(Boolean);
  const tracked = read(['diff', '--name-only', '-z', 'HEAD']);
  const untracked = read(['ls-files', '--others', '--exclude-standard', '-z']);
  return [...new Set([...tracked, ...untracked])];
}

function stagedRecords() {
  const entries = stagedEntries();
  const sizes = blobSizes(entries.map(entry => entry.sha));
  return entries
    .filter(entry => sizes.has(entry.sha))
    .map(entry => ({
      path: entry.path,
      bytes: sizes.get(entry.sha),
      readHead: () => blobHead(entry.sha),
    }));
}

function check(records, limit) {
  const maxBytes = limit * BYTES_PER_TOKEN;
  const violations = [];
  const skipped = [];

  for (const record of records) {
    if (record.bytes <= maxBytes) continue; // inside the budget

    const byPath = ignoredByPath(record.path);
    if (byPath) {
      skipped.push([record.path, byPath]);
      continue;
    }

    const head = record.readHead();
    const reason = optOutReason(head);
    if (reason) {
      skipped.push([record.path, `allowed in file: ${reason}`]);
      continue;
    }
    if (isBinary(head)) {
      skipped.push([record.path, 'binary content']);
      continue;
    }
    if (hasGeneratedMarker(head)) {
      skipped.push([record.path, 'generated code']);
      continue;
    }
    violations.push(record);
  }

  return { violations, skipped };
}

function formatBytes(bytes) {
  return `${bytes.toLocaleString('en-US')} bytes`;
}

function report(violations, skipped, limit) {
  console.error(`${violations.length} file(s) exceed the ${limit.toLocaleString('en-US')}-token file budget (bytes / ${BYTES_PER_TOKEN}).\n`);
  for (const record of violations) {
    const tokens = Math.ceil(record.bytes / BYTES_PER_TOKEN);
    console.error(`  ${record.path}`);
    console.error(`    ${formatBytes(record.bytes)} ≈ ${tokens.toLocaleString('en-US')} tokens (limit ${limit.toLocaleString('en-US')})\n`);
  }

  console.error('Split these files before committing:');
  console.error('  1. Give each file one responsibility and move the rest into new files');
  console.error('     beside it - same directory, same language. For a document, split by');
  console.error('     topic instead of by length.');
  console.error('  2. Keep the interface of the file you shrink stable, so callers do not');
  console.error('     change. Move the code out first, rewrite it afterwards.');
  console.error('  3. Fix the imports on both sides, then commit again.');
  console.error('');
  console.error('  Check the split with:  node --run check:tokens');
  console.error('');
  console.error('If a file genuinely cannot be split, state why at the top of that file:');
  console.error('  graph:allow-large-file: <reason>');
  console.error('');
  console.error('This budget covers every file an agent writes, docs and CSS included;');
  console.error('only files an agent did not write are exempt.');
  console.error('');

  if (skipped.length) {
    const shown = skipped.slice(0, 8).map(([path, why]) => `  ${path} (${why})`);
    console.error(`Skipped as not agent-authored: ${skipped.length} file(s)`);
    for (const line of shown) console.error(line);
    if (skipped.length > shown.length) console.error(`  ... and ${skipped.length - shown.length} more`);
    console.error('');
  }
}

function main() {
  const limit = tokenLimit();
  const explicit = process.argv.slice(2);
  const changed = explicit.includes('--changed');
  const paths = explicit.filter(argument => argument !== '--changed');
  const records = changed
    ? fileRecords(changedPaths().filter(path => existsSync(resolve(REPO_ROOT, path))))
    : paths.length ? fileRecords(paths) : stagedRecords();
  const { violations, skipped } = check(records, limit);

  if (violations.length) {
    report(violations, skipped, limit);
    process.exit(1);
  }

  const scope = changed ? 'changed' : paths.length ? 'named' : 'staged';
  console.log(
    `file budget: ${records.length} ${scope} file(s) within the ${limit.toLocaleString('en-US')}-token budget` +
      `${skipped.length ? `, ${skipped.length} skipped as not agent-authored` : ''}.`,
  );
}

main();
