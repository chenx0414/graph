#!/usr/bin/env python3
"""Apply the shared Graph check policy to existing and newly created worktrees."""

import json
from pathlib import Path
import shutil
import subprocess
import sys


source = Path(__file__).resolve().parent.parent
if len(sys.argv) == 3 and sys.argv[1] == "--refresh-patch":
    import difflib

    revision = subprocess.check_output(["git", "rev-parse", "--verify", "--end-of-options", sys.argv[2] + "^{commit}"], cwd=source, text=True).strip()
    patch = [f"# @generated by scripts/install-check-policy.py --refresh-patch {revision}\n"]
    for name in ("desktop/main.mjs", "desktop/console-window.mjs", "desktop/runtime-files.mjs", "tests/e2e/desktop-shell.test.ts"):
        old = subprocess.run(["git", "show", revision + ":" + name], cwd=source, capture_output=True, text=True)
        before = old.stdout.splitlines(keepends=True) if old.returncode == 0 else []
        patch.extend(difflib.unified_diff(before, (source / name).read_text().splitlines(keepends=True), fromfile="a/" + name if before else "/dev/null", tofile="b/" + name))
    (source / ".githooks/desktop-background.patch").write_text("".join(patch))
    raise SystemExit(0)
if sys.argv[1:] not in ([], ["--all"]):
    raise SystemExit("Usage: install-check-policy.py [--all | --refresh-patch <base-commit>]")
if sys.argv[1:] == ["--all"]:
    rows = subprocess.check_output(["git", "worktree", "list", "--porcelain", "-z"], text=True).split("\0")
    for row in rows:
        if row.startswith("worktree "):
            subprocess.run([sys.executable, str(Path(__file__).resolve())], cwd=row[9:], check=True)
    raise SystemExit(0)

target = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
package_path = target / "package.json"
text = package_path.read_text()
scripts = json.loads(text)["scripts"]
queue = "python3 scripts/check-queue.py"
original = "node --run check:backend && node --run typecheck && node --run lint && node --run test:report && node --run check:baseline && node --run check:evidence"
if scripts.get("check") not in (queue, original):
    raise SystemExit("Check policy: migrate the unexpected check command explicitly")
text = text.replace('"check": ' + json.dumps(scripts["check"]), '"check": ' + json.dumps(queue), 1)
if "check:run" in scripts:
    if scripts["check:run"] not in (queue, queue + " --continue", original):
        raise SystemExit("Check policy: unexpected check:run command")
    text = text.replace('"check:run": ' + json.dumps(scripts["check:run"]), '"check:run": ' + json.dumps(queue + " --continue"), 1)
else:
    entry = '"check": ' + json.dumps(queue) + ','
    text = text.replace(entry, entry + '\n    "check:run": ' + json.dumps(queue + " --continue") + ',', 1)
for name in ("test", "test:report"):
    value = scripts.get(name, "")
    if value.startswith("vitest "):
        wrapped = queue + " --continue -- node node_modules/vitest/vitest.mjs " + value[len("vitest "):]
        text = text.replace(json.dumps(name) + ": " + json.dumps(value), json.dumps(name) + ": " + json.dumps(wrapped), 1)
if text != package_path.read_text():
    package_path.write_text(text)
destination = target / "scripts/check-queue.py"
if destination != source / "scripts/check-queue.py":
    shutil.copy2(source / "scripts/check-queue.py", destination)

config_path = target / "vitest.config.ts"
config = config_path.read_text()
if "maxWorkers:" not in config:
    config = config.replace("  test: {", "  test: {\n    maxWorkers: 2,", 1)
if "bail:" not in config:
    config = config.replace("  test: {", "  test: {\n    bail: 1,", 1)
if config != config_path.read_text():
    config_path.write_text(config)

includes = []
if "createConsoleWindow" not in (target / "desktop/main.mjs").read_text():
    includes.append("desktop/main.mjs")
for name in ("desktop/console-window.mjs", "desktop/runtime-files.mjs"):
    if not (target / name).exists():
        includes.append(name)
if "GRAPH_E2E_VISIBLE_WINDOWS" not in (target / "tests/e2e/desktop-shell.test.ts").read_text():
    includes.append("tests/e2e/desktop-shell.test.ts")
if includes:
    args = ["git", "apply", "--whitespace=nowarn", *["--include=" + name for name in includes], str(source / ".githooks/desktop-background.patch")]
    subprocess.run(args[:2] + ["--check"] + args[2:], cwd=target, check=True)
    subprocess.run(args, cwd=target, check=True)

print("[check policy] Shared queue, two workers and background desktop tests configured", flush=True)
