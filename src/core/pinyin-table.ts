/** Han character → toneless pinyin. First reading wins on accidental overlap. */
const TABLE = new Map<string, string>();
for (const [syllable, characters] of Object.entries(PINYIN_GROUPS)) {
  for (const character of characters) {
    if (!TABLE.has(character)) TABLE.set(character, syllable);
  }
}

/** Toneless pinyin for one character, or null when it is not in the built-in table. */
export function pinyinFor(char: string): string | null {
  return TABLE.get(char) ?? null;
}

/** Number of characters covered by the built-in table (used by tests/diagnostics). */
